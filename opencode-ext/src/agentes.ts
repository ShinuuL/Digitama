// Gera os arquivos de agentes do OpenCode v2 (.opencode/agents/<id>.md) a partir
// do fluxo montado no painel: um orquestrador (primário) que chama, em ordem,
// os subagentes de cada etapa. Só arquivos com MARCA são trocados.

export const MARCA = "generated by Digitama OpenCode";

export type Efeito = "allow" | "ask" | "deny";

export interface Etapa {
  id: string;
  nome: string;
  descricao: string;
  instrucoes: string;
  /** provider/modelo, com #variante opcional; vazio = modelo padrão. */
  modelo: string;
  cor: string;
  editar: Efeito;
  terminal: Efeito;
  web: Efeito;
}

export interface Fluxo {
  orquestrador: { id: string; nome: string; descricao: string; modelo: string };
  etapas: Etapa[];
}

export interface Arquivo {
  nome: string;
  conteudo: string;
}

export const idValido = (id: string) => /^[a-z][a-z0-9-]{0,39}$/.test(id);

/** Converte um nome livre em id de agente ("Revisor de PR" → "revisor-de-pr"). */
export function paraId(nome: string): string {
  const s = nome
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
  return /^[a-z]/.test(s) ? s : s ? "a-" + s.slice(0, 38) : "";
}

// JSON é YAML válido: assim nenhum texto quebra o frontmatter.
const y = (v: string) => JSON.stringify(v);

function frontmatter(campos: [string, string | undefined][], regras: { action: string; resource: string; effect: Efeito }[]): string {
  const linhas = ["---"];
  for (const [k, v] of campos) if (v) linhas.push(`${k}: ${v}`);
  if (regras.length) {
    linhas.push("permissions:");
    for (const r of regras) linhas.push(`  - action: ${y(r.action)}`, `    resource: ${y(r.resource)}`, `    effect: ${r.effect}`);
  }
  linhas.push("---");
  return linhas.join("\n");
}

function regrasDaEtapa(e: Etapa) {
  return [
    { action: "edit", resource: "*", effect: e.editar },
    { action: "shell", resource: "*", effect: e.terminal },
    { action: "webfetch", resource: "*", effect: e.web },
    { action: "websearch", resource: "*", effect: e.web },
  ];
}

export function validar(f: Fluxo): string[] {
  const erros: string[] = [];
  const ids = [f.orquestrador.id, ...f.etapas.map((e) => e.id)];
  if (!f.etapas.length) erros.push("Arraste pelo menos uma função para o fluxo.");
  for (const id of ids) if (!idValido(id)) erros.push(`Id inválido: "${id}" (use letras minúsculas, números e hífen).`);
  const repetidos = ids.filter((id, i) => ids.indexOf(id) !== i);
  if (repetidos.length) erros.push(`Ids repetidos: ${[...new Set(repetidos)].join(", ")}.`);
  for (const e of f.etapas) if (!e.descricao.trim()) erros.push(`"${e.nome}" precisa de uma descrição (é ela que o orquestrador lê).`);
  return erros;
}

export function gerar(f: Fluxo): Arquivo[] {
  const arquivos: Arquivo[] = [];
  for (const e of f.etapas) {
    const fm = frontmatter(
      [
        ["description", y(e.descricao.trim())],
        ["mode", "subagent"],
        ["model", e.modelo ? y(e.modelo) : undefined],
        ["color", /^#[0-9a-fA-F]{6}$/.test(e.cor) ? y(e.cor) : undefined],
      ],
      regrasDaEtapa(e),
    );
    arquivos.push({ nome: `${e.id}.md`, conteudo: `${fm}\n<!-- ${MARCA} -->\n\n${e.instrucoes.trim() || e.descricao.trim()}\n` });
  }

  const o = f.orquestrador;
  const regras = [
    { action: "subagent", resource: "*", effect: "deny" as Efeito },
    ...f.etapas.map((e) => ({ action: "subagent", resource: e.id, effect: "allow" as Efeito })),
  ];
  const passos = f.etapas.map((e, i) => `${i + 1}. **${e.nome}** — chame o subagente \`${e.id}\`: ${e.descricao.trim()}`).join("\n");
  const corpo = [
    `Você coordena um fluxo de ${f.etapas.length} etapa(s). Para cada pedido do usuário, siga esta ordem:`,
    "",
    passos,
    "",
    "Passe a cada subagente o pedido original e o resultado útil da etapa anterior. Se uma etapa falhar ou apontar problema, volte à etapa que resolve antes de seguir. No fim, responda ao usuário com um resumo curto do que cada etapa fez.",
  ].join("\n");
  const fm = frontmatter(
    [
      ["description", y(o.descricao.trim() || `Orquestra: ${f.etapas.map((e) => e.nome).join(" → ")}`)],
      ["mode", "primary"],
      ["model", o.modelo ? y(o.modelo) : undefined],
    ],
    regras,
  );
  // o fluxo vai junto, para o painel reabrir e editar depois
  const dados = Buffer.from(JSON.stringify(f), "utf8").toString("base64");
  arquivos.push({ nome: `${o.id}.md`, conteudo: `${fm}\n<!-- ${MARCA} -->\n<!-- fluxo:${dados} -->\n\n${corpo}\n` });
  return arquivos;
}

/** Recupera o fluxo salvo dentro de um orquestrador gerado por nós. */
export function lerFluxo(conteudo: string): Fluxo | undefined {
  const m = conteudo.match(/<!-- fluxo:([A-Za-z0-9+/=]+) -->/);
  if (!m || !conteudo.includes(MARCA)) return undefined;
  try {
    return JSON.parse(Buffer.from(m[1], "base64").toString("utf8"));
  } catch {
    return undefined;
  }
}
