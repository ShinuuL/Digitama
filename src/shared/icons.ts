const cache = new Map<string, string>();

/** O ícone como data URL PNG, na cor `color`, com pixel de `px`. */
export function icon(name: keyof typeof ICONS | string, color = "#ffd23f", px = 3): string {
  const key = `${name}:${color}:${px}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const grid = ICONS[name] ?? ICONS.star;
  const c = document.createElement("canvas");
  c.width = c.height = 12 * px;
  const g = c.getContext("2d")!;
  grid.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === ".") continue;
      g.fillStyle = ch === "k" ? "#0b0820" : ch === "w" ? "#ffffff" : color;
      g.fillRect(x * px, y * px, px, px);
    }
  });
  const url = c.toDataURL("image/png");
  cache.set(key, url);
  return url;
}

/** Um <img> com o ícone, já com pixels nítidos. */
export function iconImg(name: string, color?: string, px?: number): HTMLImageElement {
  const img = new Image();
  img.src = icon(name, color, px);
  img.className = "px-icon";
  img.draggable = false;
  return img;
}
