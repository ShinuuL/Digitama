//! OpenCode: achar o executável em qualquer instalação do Windows e instalar o
//! plugin que liga o OpenCode ao pet.
//!
//! O plugin (`~/.config/opencode/plugins/digitama.js`) é adaptado do plugin do
//! Coucou (MIT, © Louis Raillé). Ele repassa os eventos ao relay sem nunca
//! segurar o OpenCode, e responde uma permissão só quando você clica no balão.

use std::path::PathBuf;

use serde::Serialize;

/// Marca de todo plugin escrito pelo Digitama: só esse arquivo é trocado ou removido.
const GENERATED: &str = "generated by Digitama";

fn home() -> PathBuf {
    std::env::var_os("USERPROFILE").map(PathBuf::from).unwrap_or_default()
}

fn env_path(var: &str) -> Option<PathBuf> {
    std::env::var_os(var).map(PathBuf::from)
}

/// Onde o OpenCode pode estar: caminho configurado, PATH, instalador oficial,
/// Scoop, Chocolatey, Bun e o pacote npm (o binário de verdade, não o .cmd).
pub fn find_opencode(custom: &str) -> Option<PathBuf> {
    if !custom.trim().is_empty() {
        let p = PathBuf::from(custom.trim());
        return p.exists().then_some(p);
    }
    let mut candidates: Vec<PathBuf> = Vec::new();
    if let Some(path) = std::env::var_os("PATH") {
        for dir in std::env::split_paths(&path) {
            candidates.push(dir.join("opencode.exe"));
        }
    }
    let home = home();
    let appdata = env_path("APPDATA").unwrap_or_default();
    candidates.extend([
        home.join(".opencode").join("bin").join("opencode.exe"),
        home.join("scoop").join("shims").join("opencode.exe"),
        PathBuf::from(r"C:\ProgramData\chocolatey\bin\opencode.exe"),
        home.join(".bun").join("bin").join("opencode.exe"),
    ]);
    let npm = appdata.join("npm").join("node_modules").join("opencode-ai").join("node_modules");
    for pkg in ["opencode-windows-x64", "opencode-windows-x64-baseline", "opencode-windows-arm64"] {
        candidates.push(npm.join(pkg).join("bin").join("opencode.exe"));
    }
    if let Some(found) = candidates.into_iter().find(|p| p.exists()) {
        return Some(found);
    }
    // Último recurso: o atalho .cmd do npm (roda via cmd.exe, ver `command`).
    std::env::var_os("PATH").and_then(|path| {
        std::env::split_paths(&path).map(|d| d.join("opencode.cmd")).find(|p| p.exists())
    })
}

/// Um `Command` para o executável, passando por `cmd /C` quando é um .cmd do npm.
/// Os argumentos são sempre nossos (flags, ids, caminhos); o texto do usuário vai
/// pelo stdin, nunca pela linha de comando.
pub fn command(exe: &std::path::Path) -> std::process::Command {
    use std::os::windows::process::CommandExt;
    let is_cmd = exe.extension().and_then(|e| e.to_str()).is_some_and(|e| e.eq_ignore_ascii_case("cmd"));
    let mut cmd = if is_cmd {
        let mut c = std::process::Command::new("cmd");
        c.arg("/D").arg("/C").arg(exe);
        c
    } else {
        std::process::Command::new(exe)
    };
    cmd.creation_flags(0x0800_0000); // CREATE_NO_WINDOW
    cmd
}

/// `provedor/modelo` seguro para ir na linha de comando.
pub fn valid_model(model: &str) -> bool {
    !model.is_empty()
        && model.len() < 200
        && model.chars().all(|c| c.is_ascii_alphanumeric() || "._-/:@+".contains(c))
}

/// Roda o OpenCode com argumentos fixos e devolve stdout+stderr.
pub fn run(custom: &str, args: &[&str]) -> Result<String, String> {
    let exe = find_opencode(custom).ok_or("OpenCode não encontrado")?;
    let out = command(&exe)
        .args(args)
        .stdin(std::process::Stdio::null())
        .output()
        .map_err(|e| e.to_string())?;
    let text = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    if out.status.success() { Ok(text.trim().to_string()) } else { Err(text.trim().to_string()) }
}

/// A lista de `opencode models`: uma linha `provedor/modelo` por modelo.
pub fn models(custom: &str) -> Result<Vec<String>, String> {
    let text = run(custom, &["models"])?;
    Ok(text
        .lines()
        .map(str::trim)
        .filter(|l| l.contains('/') && valid_model(l))
        .map(str::to_string)
        .collect())
}

// ── Plugin ───────────────────────────────────────────────────────────────────

/// `~/.config/opencode/plugins/digitama.js` (o OpenCode lê ~/.config também no
/// Windows; respeita XDG_CONFIG_HOME se existir).
pub fn plugin_path() -> PathBuf {
    let base = env_path("XDG_CONFIG_HOME").unwrap_or_else(|| home().join(".config"));
    base.join("opencode").join("plugins").join("digitama.js")
}

const PLUGIN: &str = r#"// Plugin do Digitama para o OpenCode — generated by Digitama.
// Repassa os eventos do OpenCode ao pet (digitama-hook). Nunca segura o
// OpenCode: com o Digitama fechado, nada acontece. Uma permissão só é
// respondida quando você clica no balão do pet; senão o OpenCode pergunta como
// sempre, e quem responder primeiro vale.
import { spawn } from "node:child_process";

const HOOK = {HOOK};
const SESSION = {
  "session.created": "SessionStart",
  "session.idle": "Stop",
  "session.error": "StopFailure",
  "session.deleted": "SessionEnd",
};

function relay(payload, wait) {
  return new Promise((resolve) => {
    let out = "";
    try {
      const p = spawn(HOOK, ["--agent", "opencode"], {
        stdio: ["pipe", wait ? "pipe" : "ignore", "ignore"],
        windowsHide: true,
      });
      p.on("error", () => resolve(""));
      p.stdin.on("error", () => {});
      if (wait) {
        p.stdout.on("data", (d) => (out += d));
        p.on("close", () => resolve(out.trim()));
      }
      p.stdin.end(JSON.stringify(payload) + "\n");
      if (!wait) {
        p.unref();
        resolve("");
      }
    } catch {
      resolve("");
    }
  });
}

const fire = (hook_event_name, data) => void relay({ hook_event_name, ...data }, false);
const props = (event) => event?.properties ?? event?.data ?? {};

// A API de permissões mudou entre versões do OpenCode: tenta a nova e a antiga.
async function answer(client, req, decision) {
  const ok = decision === "allow";
  const attempts = [
    () => client?.permission?.reply?.({ sessionID: req.sessionID, requestID: req.id, decision: ok ? "once" : "reject" }),
    () =>
      client?.postSessionIdPermissionsPermissionId?.({
        path: { id: req.sessionID, permissionID: req.id },
        body: { response: ok ? "once" : "reject" },
      }),
  ];
  for (const attempt of attempts) {
    try {
      const r = attempt();
      if (r) {
        await r;
        return;
      }
    } catch {}
  }
}

async function askPet(client, base, req) {
  const resources = Array.isArray(req.resources)
    ? req.resources
    : Array.isArray(req.patterns)
      ? req.patterns
      : req.pattern
        ? [].concat(req.pattern)
        : [];
  const action = req.action || req.permission || req.type || "permissão";
  const title = req.title || [action, resources.join(", ")].filter(Boolean).join(" · ");
  const sessionID = req.sessionID || base.session_id;
  const decision = await relay(
    {
      hook_event_name: "PermissionRequest",
      ...base,
      session_id: sessionID,
      tool_name: action,
      tool_input: { command: title },
      opencode_request_id: req.id || "",
    },
    true,
  );
  if (decision === "allow" || decision === "deny") await answer(client, { id: req.id, sessionID }, decision);
}

export const DigitamaPlugin = async ({ client, directory } = {}) => ({
  event: async ({ event }) => {
    const type = event?.type;
    const p = props(event);
    const base = { session_id: p.sessionID || p.info?.id || "", cwd: directory || "" };
    if (SESSION[type]) return fire(SESSION[type], base);
    if (type === "permission.asked" || type === "permission.updated") {
      // sem await: o OpenCode segue livre enquanto o balão espera o clique
      void askPet(client, base, p.request ?? p);
      return;
    }
    if (type === "permission.replied") {
      return fire("PermissionReplied", { ...base, opencode_request_id: p.requestID || p.permissionID || p.id || "" });
    }
    if (type === "form.created" || type === "question.asked") {
      const form = p.form ?? p;
      return fire("Notification", {
        ...base,
        notification_type: "question",
        message: form.title || form.question || "O OpenCode tem uma pergunta para você.",
      });
    }
  },
  "tool.execute.before": async (input, output) =>
    fire("PreToolUse", {
      session_id: input?.sessionID || "",
      cwd: directory || "",
      tool_name: typeof input?.tool === "string" ? input.tool : "",
      tool_input: output?.args ?? null,
    }),
  "tool.execute.after": async (input) =>
    fire("PostToolUse", {
      session_id: input?.sessionID || "",
      cwd: directory || "",
      tool_name: typeof input?.tool === "string" ? input.tool : "",
    }),
});
"#;

pub fn plugin_source(hook_exe: &str) -> String {
    let quoted = serde_json::to_string(hook_exe).unwrap_or_else(|_| "\"\"".into());
    PLUGIN.replace("{HOOK}", &quoted)
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PluginStatus {
    pub installed: bool,
    pub up_to_date: bool,
    /// Existe um digitama.js que não foi escrito por nós: não mexemos.
    pub foreign: bool,
    pub path: String,
    pub found: Option<String>,
    pub version: Option<String>,
}

pub fn status(hook_exe: &str, custom: &str) -> PluginStatus {
    let path = plugin_path();
    let current = std::fs::read_to_string(&path).ok();
    let ours = current.as_deref().is_some_and(|t| t.contains(GENERATED));
    PluginStatus {
        installed: ours,
        up_to_date: current.as_deref() == Some(plugin_source(hook_exe).as_str()),
        foreign: current.is_some() && !ours,
        path: path.to_string_lossy().into_owned(),
        found: find_opencode(custom).map(|p| p.to_string_lossy().into_owned()),
        version: run(custom, &["--version"]).ok().map(|v| v.lines().next().unwrap_or_default().to_string()),
    }
}

/// O diff do que vai mudar (o arquivo inteiro é nosso).
pub fn preview(install: bool, hook_exe: &str) -> Result<String, String> {
    let path = plugin_path();
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    if !current.is_empty() && !current.contains(GENERATED) {
        return Err(format!("{} não foi escrito pelo Digitama — nada foi alterado.", path.display()));
    }
    let next = if install { plugin_source(hook_exe) } else { String::new() };
    Ok(crate::hooks_install::line_diff(&current, &next))
}

pub fn apply(install: bool, hook_exe: &str) -> Result<String, String> {
    let path = plugin_path();
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    if !current.is_empty() && !current.contains(GENERATED) {
        return Err(format!("{} não foi escrito pelo Digitama — nada foi alterado.", path.display()));
    }
    if install {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
        }
        std::fs::write(&path, plugin_source(hook_exe)).map_err(|e| e.to_string())?;
    } else if path.exists() {
        std::fs::remove_file(&path).map_err(|e| e.to_string())?;
    }
    Ok(path.to_string_lossy().into_owned())
}

