/// `~/.config/opencode/plugins/digitama.js` (o OpenCode lê ~/.config também no
/// Windows; respeita XDG_CONFIG_HOME se existir).
pub fn plugin_path() -> PathBuf {
    let base = env_path("XDG_CONFIG_HOME").unwrap_or_else(|| home().join(".config"));
    base.join("opencode").join("plugins").join("digitama.js")
}

const PLUGIN: &str = r#"// Plugin do Digitama para o OpenCode v2 — generated by Digitama.
// Repassa os eventos do OpenCode ao pet (digitama-hook). Nunca segura o
// OpenCode: com o Digitama fechado, nada acontece. Uma permissão só é
// respondida quando você clica no balão do pet; senão o OpenCode pergunta como
// sempre, e quem responder primeiro vale.
import { spawn } from "node:child_process";

const HOOK = {HOOK};
// Eventos de sessão do OpenCode v2 → nomes dos hooks do Claude Code que o pet entende.
const SESSION = {
  "session.created": "SessionStart",
  "session.execution.started": "UserPromptSubmit",
  "session.execution.succeeded": "Stop",
  "session.execution.failed": "StopFailure",
  "session.execution.cancelled": "Stop",
  "session.deleted": "SessionEnd",
};

function relay(payload, wait) {
  return new Promise((resolve) => {
    let out = "";
    try {
      const p = spawn(HOOK, ["--agent", "opencode"], {
        stdio: ["pipe", wait ? "pipe" : "ignore", "ignore"],
        windowsHide: true,
      });
      p.on("error", () => resolve(""));
      p.stdin.on("error", () => {});
      if (wait) {
        p.stdout.on("data", (d) => (out += d));
        p.on("close", () => resolve(out.trim()));
      }
      p.stdin.end(JSON.stringify(payload) + "\n");
      if (!wait) {
        p.unref();
        resolve("");
      }
    } catch {
      resolve("");
    }
  });
}

const fire = (hook_event_name, data) => void relay({ hook_event_name, ...data }, false);

async function askPet(ctx, base, req) {
  const resources = Array.isArray(req.resources) ? req.resources : [];
  const action = req.action || "permissão";
  const title = [action, resources.join(", ")].filter(Boolean).join(" · ");
  const decision = await relay(
    {
      hook_event_name: "PermissionRequest",
      ...base,
      tool_name: action,
      tool_input: { command: title },
      opencode_request_id: req.id || "",
    },
    true,
  );
  if (decision !== "allow" && decision !== "deny") return;
  try {
    await ctx.permission.reply({ sessionID: req.sessionID, requestID: req.id, decision: decision === "allow" ? "once" : "reject" });
  } catch {} // já respondida no OpenCode: vale quem respondeu primeiro
}

export default {
  id: "digitama",
  async setup(ctx) {
    const cwd = ctx.location?.directory || "";
    const tools = new Map(); // id da chamada → nome da ferramenta
    const ac = new AbortController();
    const onEvent = (event) => {
      const type = event?.type || "";
      const d = event?.data ?? {};
      const base = { session_id: d.sessionID || d.id || "", cwd: event?.location?.directory || cwd };
      if (SESSION[type]) fire(SESSION[type], base);
      else if (type === "permission.asked") void askPet(ctx, base, d); // sem await: o OpenCode segue livre
      else if (type === "permission.replied") fire("PermissionReplied", { ...base, opencode_request_id: d.requestID || "" });
      else if (type === "form.created" || type === "session.form.created") {
        fire("Notification", { ...base, notification_type: "question", message: d.title || "O OpenCode tem uma pergunta para você." });
      } else if (type === "session.tool.input.started" && d.id) tools.set(d.id, d.name || "");
      else if (type === "session.tool.called") {
        fire("PreToolUse", { ...base, tool_name: tools.get(d.id) || d.name || "", tool_input: d.input ?? null });
      } else if (type === "session.tool.success" || type === "session.tool.failed") {
        fire(type === "session.tool.success" ? "PostToolUse" : "PostToolUseFailure", { ...base, tool_name: tools.get(d.id) || d.name || "" });
        tools.delete(d.id);
      }
    };
    // Se a assinatura de eventos cair (erro ou fim do fluxo), assina de novo com
    // espera crescente (1 s → 30 s); sem isso o pet ficava mudo até reiniciar o OpenCode.
    (async () => {
      let wait = 1000;
      while (!ac.signal.aborted) {
        try {
          for await (const event of ctx.event.subscribe({ signal: ac.signal })) {
            wait = 1000;
            try {
              onEvent(event);
            } catch {} // um evento estranho não derruba a assinatura
          }
        } catch {}
        if (ac.signal.aborted) break;
        await new Promise((r) => setTimeout(r, wait));
        wait = Math.min(wait * 2, 30000);
      }
    })();
    return () => ac.abort();
  },
};
"#;

pub fn plugin_source(hook_exe: &str) -> String {
    let quoted = serde_json::to_string(hook_exe).unwrap_or_else(|_| "\"\"".into());
    PLUGIN.replace("{HOOK}", &quoted)
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct PluginStatus {
    pub installed: bool,
    pub up_to_date: bool,
    /// Existe um digitama.js que não foi escrito por nós: não mexemos.
    pub foreign: bool,
    pub path: String,
    pub found: Option<String>,
    pub version: Option<String>,
}

pub fn status(hook_exe: &str, custom: &str) -> PluginStatus {
    let path = plugin_path();
    let current = std::fs::read_to_string(&path).ok();
    let ours = current.as_deref().is_some_and(|t| t.contains(GENERATED));
    PluginStatus {
        installed: ours,
        up_to_date: current.as_deref() == Some(plugin_source(hook_exe).as_str()),
        foreign: current.is_some() && !ours,
        path: path.to_string_lossy().into_owned(),
        found: find_opencode(custom).map(|p| p.to_string_lossy().into_owned()),
        version: run(custom, &["--version"]).ok().map(|v| v.lines().next().unwrap_or_default().to_string()),
    }
}

/// O diff do que vai mudar (o arquivo inteiro é nosso).
pub fn preview(install: bool, hook_exe: &str) -> Result<String, String> {
    let path = plugin_path();
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    if !current.is_empty() && !current.contains(GENERATED) {
        return Err(format!("{} não foi escrito pelo Digitama — nada foi alterado.", path.display()));
    }
    let next = if install { plugin_source(hook_exe) } else { String::new() };
    Ok(crate::hooks_install::line_diff(&current, &next))
}

pub fn apply(install: bool, hook_exe: &str) -> Result<String, String> {
    let path = plugin_path();
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    if !current.is_empty() && !current.contains(GENERATED) {
        return Err(format!("{} não foi escrito pelo Digitama — nada foi alterado.", path.display()));
    }
    if install {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
        }
        std::fs::write(&path, plugin_source(hook_exe)).map_err(|e| e.to_string())?;
    } else if path.exists() {
        std::fs::remove_file(&path).map_err(|e| e.to_string())?;
    }
    Ok(path.to_string_lossy().into_owned())
}

